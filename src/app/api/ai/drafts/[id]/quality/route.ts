import { NextRequest, NextResponse } from 'next/server';
import { reviewDraft } from '@/ai/actions';
import { requireOwnedCampaign } from '@/ai/access';
import { AiNotFoundError } from '@/ai/errors';
import { requireConfiguredProvider } from '@/ai/provider';
import storage from '@/lib/storage';
import { rateLimiter } from '@/lib/rateLimit';
import { aiErrorResponse } from '@/app/api/ai/errors';

// Re-runs the advisory review for one generated draft. It never edits text,
// approves the draft, or publishes anything.
export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const generated = await storage.getGeneratedPostByDraftId(id);
    if (!generated) throw new AiNotFoundError('This draft was not generated by a campaign.');
    const { project, campaign } = await requireOwnedCampaign(request, generated.campaignId);
    const limit = rateLimiter.check(request, {
      limit: 30,
      windowMs: 60_000,
      keyPrefix: 'ai-quality',
    });
    if (!limit.success) return rateLimiter.createResponse(limit);
    const provider = requireConfiguredProvider();
    const quality = await reviewDraft({ campaign, draftId: id, project, provider });
    return NextResponse.json({ quality });
  } catch (error) {
    return aiErrorResponse(error);
  }
}
