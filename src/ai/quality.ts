import { checkDraft } from '../posting/checks';
import storage from '../lib/storage';
import type { Draft, Project } from '../types/index';
import type { AgentRuntime } from './execution';
import { asNumber, asObjectArray, asString, asStringArray, parseJsonObject } from './json';
import { qualityPrompt } from './prompts';
import type {
  BrandProfile,
  Campaign,
  QualityIssue,
  QualityResult,
  ResearchSource,
} from './types';

export const QUALITY_DISCLAIMER =
  'This score is advisory, not objective truth. Crewlink compares claims only with the sources it retrieved, does not open links to test them, and cannot detect every misleading statement.';

const PROMO_PATTERN =
  /\b(revolutionary|game[- ]changing|guaranteed|world[- ]class|best ever|unprecedented|must[- ]have|instant results)\b/gi;

function extractUrls(text: string): string[] {
  return Array.from(text.matchAll(/https?:\/\/[^\s<>"')]+/gi))
    .map((match) => match[0].replace(/[.,;:!?]+$/, ''))
    .slice(0, 20);
}

function statsIn(text: string): string[] {
  const matches = text.match(
    /\b\d+(?:[.,]\d+)?\s?(?:%|(?:percent|x|users|stars|downloads|views|followers|signups|conversions)\b)/gi
  );
  return Array.from(new Set((matches || []).map((match) => match.trim()))).slice(0, 8);
}

function repeatedSentences(text: string): string[] {
  const seen = new Set<string>();
  const repeated = new Set<string>();
  for (const sentence of text.split(/(?<=[.!?])\s+/)) {
    const key = sentence.replace(/\s+/g, ' ').trim().toLowerCase();
    if (key.length < 40) continue;
    if (seen.has(key)) repeated.add(sentence.trim().slice(0, 120));
    seen.add(key);
  }
  return Array.from(repeated).slice(0, 3);
}

export async function evaluateDraft(options: {
  draft: Draft;
  campaign: Campaign;
  brand: BrandProfile | null;
  project: Project;
  sources: ResearchSource[];
  runtime: AgentRuntime;
  joinUrl: string;
}): Promise<QualityResult> {
  const generated = await storage.getGeneratedPostByDraftId(options.draft.id);
  if (!generated) {
    throw new Error('This draft was not generated by an AI campaign.');
  }

  const allDrafts = await storage.getDraftsByProject(options.project.id);
  const staticChecks = checkDraft(
    {
      ownerName: options.project.repoOwner,
      repoName: options.project.repoName,
      repoFullName: options.project.repoFullName,
      isPrivate: options.project.isPrivate,
      joinUrl: options.joinUrl,
      roles: options.project.roles,
      description: options.project.description,
      approvedDrafts: allDrafts
        .filter((d) => d.status === 'approved' && d.approvedText && d.approvedAt && d.id !== options.draft.id)
        .map((d) => ({
          platformId: d.platformId,
          approvedText: d.approvedText!,
          approvedAt: d.approvedAt!,
        })),
    },
    options.draft.platformId,
    options.draft.text,
    options.draft.threadParts,
    options.draft.platformId === 'reddit'
      ? {
          title: options.draft.title,
          subreddit: options.draft.subreddit,
          submissionType: options.draft.submissionType,
          linkUrl: options.draft.linkUrl,
        }
      : undefined
  );

  const deterministic: QualityIssue[] = staticChecks.map((check) => ({
    code: check.code,
    severity: check.level === 'error' ? 'error' : 'warning',
    message: check.message,
  }));

  const urls = extractUrls(options.draft.text);
  for (const url of urls) {
    try {
      new URL(url);
    } catch {
      deterministic.push({
        code: 'invalid_link',
        severity: 'error',
        message: `A link is not a valid URL: ${url.slice(0, 120)}`,
      });
    }
  }
  if (urls.length) {
    deterministic.push({
      code: 'links_not_verified',
      severity: 'info',
      message: 'Links are listed but not opened or verified by Crewlink.',
    });
  }

  const sourceText = options.sources
    .map((source) =>
      [source.title, source.summary, source.publisher].filter(Boolean).join(' ')
    )
    .join(' ')
    .toLowerCase();

  for (const stat of statsIn(options.draft.text)) {
    if (!options.sources.length) {
      deterministic.push({
        code: 'unsupported_statistic',
        severity: 'warning',
        message: `No retrieved source supports "${stat}". Label it as your own figure or remove it.`,
      });
    } else if (!sourceText.includes(stat.toLowerCase())) {
      deterministic.push({
        code: 'unverified_statistic',
        severity: 'warning',
        message: `Crewlink could not match "${stat}" to a retrieved source. Verify it before publishing.`,
      });
    }
  }

  for (const sentence of repeatedSentences(options.draft.text)) {
    deterministic.push({
      code: 'repetitive_content',
      severity: 'warning',
      message: `A sentence is repeated: ${sentence}`,
    });
  }

  if (options.brand) {
    const lower = options.draft.text.toLowerCase();
    for (const word of options.brand.avoidWords) {
      const needle = word.trim().toLowerCase();
      if (needle && lower.includes(needle)) {
        deterministic.push({
          code: 'brand_word_avoided',
          severity: 'warning',
          message: `The draft uses a word the brand profile asks to avoid: ${word}`,
        });
      }
    }
    for (const topic of options.brand.avoidTopics) {
      const needle = topic.trim().toLowerCase();
      if (needle && lower.includes(needle)) {
        deterministic.push({
          code: 'brand_topic_avoided',
          severity: 'warning',
          message: `The draft mentions an avoided topic: ${topic}`,
        });
      }
    }
  }

  const promotional = Array.from(new Set(Array.from(options.draft.text.matchAll(PROMO_PATTERN)).map((m) => m[0].toLowerCase())));
  if (promotional.length) {
    deterministic.push({
      code: 'promotional_language',
      severity: 'warning',
      message: `Strongly promotional wording: ${promotional.slice(0, 5).join(', ')}`,
    });
  }

  const prompt = qualityPrompt({
    text: options.draft.text,
    platformId: options.draft.platformId,
    brand: options.brand,
    sources: options.sources,
    staticIssues: deterministic.map((issue) => ({
      code: issue.code,
      severity: issue.severity,
      message: issue.message,
    })),
  });
  const response = await options.runtime.complete({
    task: 'quality',
    system: prompt.system,
    user: prompt.user,
    json: true,
    maxOutputTokens: 1600,
    meta: {
      text: options.draft.text,
      platformId: options.draft.platformId,
      staticIssues: deterministic.map((issue) => ({
        code: issue.code,
        severity: issue.severity,
        message: issue.message,
      })),
      sources: options.sources.map((source) => ({
        title: source.title,
        url: source.url,
      })),
    },
  });
  const parsed = parseJsonObject(response.text);

  const allowedUrls = new Set(options.sources.map((source) => source.url.toLowerCase()));
  const modelIssues: QualityIssue[] = asObjectArray(parsed.issues, 30)
    .map((row) => ({
      code: asString(row.code, 'quality_issue').slice(0, 80),
      severity:
        row.severity === 'error'
          ? ('error' as const)
          : row.severity === 'warning'
            ? ('warning' as const)
            : ('info' as const),
      message: asString(row.message).slice(0, 500),
      sourceUrls: asStringArray(row.sourceUrls, 5).filter((url) =>
        allowedUrls.has(url.toLowerCase())
      ),
    }))
    .filter((issue) => issue.message);

  const merged = new Map<string, QualityIssue>();
  for (const issue of [...deterministic, ...modelIssues]) {
    merged.set(`${issue.code}:${issue.message}`, issue);
  }
  const issues = Array.from(merged.values()).slice(0, 40);
  const errors = issues.filter((issue) => issue.severity === 'error').length;
  const warnings = issues.filter((issue) => issue.severity === 'warning').length;
  let score = Math.max(0, Math.min(100, Math.round(asNumber(parsed.score, 70))));
  if (errors > 0) score = Math.min(score, 40);
  if (warnings >= 3) score = Math.min(score, 70);

  const result: QualityResult = {
    score,
    verificationStatus: 'unverified',
    disclaimer: QUALITY_DISCLAIMER,
    issues,
    improvements: asStringArray(parsed.improvements, 10),
    sourceUrls: asStringArray(parsed.sourceUrls, 10).filter((url) =>
      allowedUrls.has(url.toLowerCase())
    ),
    linkCheck: 'not_checked',
    checkedAt: new Date().toISOString(),
    provider: response.provider,
    model: response.model,
  };

  await storage.updateGeneratedPostQuality(generated.id, result);
  return result;
}
